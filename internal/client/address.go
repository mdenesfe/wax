package client

import (
	"bytes"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"fmt"
	"slices"
	"strconv"
	"strings"
	"time"

	wabin "github.com/mdenesfe/wax/internal/binary"
)

// signalAddressName is the Signal "name" of a JID's user: the user part,
// suffixed with the agent for non-phone-number domains so that a phone
// number and a LID with the same digits never collide.
func signalAddressName(j wabin.JID) string {
	name := j.User
	switch j.Server {
	case wabin.ServerLID:
		name += "_1"
	case wabin.ServerHosted:
		name += "_128"
	case wabin.ServerHostedLID:
		name += "_129"
	default:
		if j.RawAgent > 0 {
			name += "_" + strconv.Itoa(int(j.RawAgent))
		}
	}
	return name
}

// signalAddress identifies one device's session: "name.device".
func signalAddress(j wabin.JID) string {
	return signalAddressName(j) + "." + strconv.Itoa(int(j.Device))
}

// adString is the canonical device form used in participant list hashes.
func adString(j wabin.JID) string {
	return fmt.Sprintf("%s.%d:%d@%s", j.User, j.RawAgent, j.Device, j.Server)
}

// participantListHash is the "phash" the server compares against its view
// of the recipient devices; a mismatch means our device list is stale.
func participantListHash(devices []wabin.JID) string {
	s := make([]string, len(devices))
	for i, d := range devices {
		s[i] = adString(d)
	}
	slices.Sort(s)
	sum := sha256.Sum256([]byte(strings.Join(s, "")))
	return "2:" + base64.RawStdEncoding.EncodeToString(sum[:6])
}

// webMessageIDPrefix marks message ids generated by web clients.
const webMessageIDPrefix = "3EB0"

// newMessageID generates a message id like WhatsApp Web: 3EB0 followed by
// 18 uppercase hex characters derived from time, our JID and randomness.
func newMessageID(own wabin.JID) string {
	data := make([]byte, 8, 8+32+16)
	binary.BigEndian.PutUint64(data, uint64(time.Now().Unix()))
	if own.User != "" {
		data = append(data, own.User...)
		data = append(data, "@c.us"...)
	}
	var rnd [16]byte
	_, _ = rand.Read(rnd[:])
	data = append(data, rnd[:]...)
	sum := sha256.Sum256(data)
	return webMessageIDPrefix + strings.ToUpper(hex.EncodeToString(sum[:9]))
}

// Message padding: WhatsApp appends 1-15 bytes, each equal to the padding
// length, to every plaintext before Signal encryption (v2 messages).

func padMessage(plaintext []byte) []byte {
	var b [1]byte
	_, _ = rand.Read(b[:])
	n := b[0] & 0x0f
	if n == 0 {
		n = 0x0f
	}
	return append(plaintext, bytes.Repeat([]byte{n}, int(n))...)
}

var errBadPadding = errors.New("client: plaintext has invalid padding")

func unpadMessage(plaintext []byte) ([]byte, error) {
	if len(plaintext) == 0 {
		return nil, errBadPadding
	}
	n := int(plaintext[len(plaintext)-1])
	if n == 0 || n > len(plaintext) {
		return nil, errBadPadding
	}
	for _, b := range plaintext[len(plaintext)-n:] {
		if int(b) != n {
			return nil, errBadPadding
		}
	}
	return plaintext[:len(plaintext)-n], nil
}
